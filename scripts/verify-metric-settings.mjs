import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { createServer } from 'node:http';
import path from 'node:path';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const root=path.resolve('.workbuddy-local/metric-governance');
const db=new DatabaseSync(path.join(root,'test.sqlite'));
const original=db.prepare("SELECT role FROM tenant_user WHERE username='admin'").get();
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
let requests=0;
const server=createServer(async(req,res)=>{for await(const _ of req){} requests++;res.setHeader('content-type','application/json');res.end(JSON.stringify({data:[{embedding:[1,0,0]}]}));});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const base='http://127.0.0.1:3010';
const context=await browser.newContext({viewport:{width:1440,height:1050}});
try {
  assert.equal((await context.request.get(`${base}/api/settings/metric-embedding`)).status(),401);
  db.prepare("UPDATE tenant_user SET role='admin' WHERE username='admin'").run();
  assert.equal((await context.request.post(`${base}/api/login`,{data:{username:'admin',password:'admin'}})).status(),200);
  assert.equal((await context.request.get(`${base}/api/settings/metric-embedding`)).status(),403);
  db.prepare("UPDATE tenant_user SET role='administrator' WHERE username='admin'").run();
  await context.request.post(`${base}/api/login`,{data:{username:'admin',password:'admin'}});
  const page=await context.newPage(); const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`${base}/settings`);
  await page.getByRole('button',{name:'模型配置',exact:true}).click();
  const vector=page.locator('section').filter({has:page.getByRole('heading',{name:'向量模型',exact:true})});
  await vector.getByRole('switch').click();
  await vector.getByLabel('服务地址（OpenAI 兼容）').fill(`http://127.0.0.1:${server.address().port}/v1`);
  await vector.getByLabel('模型名称',{exact:true}).fill('fixture-embedding');
  await page.locator('section').filter({has:page.getByRole('heading',{name:'向量模型',exact:true})}).getByLabel('API Key',{exact:false}).fill('fixture-secret');
  await vector.getByRole('button',{name:'测试连接',exact:true}).click();
  await page.getByRole('status').filter({hasText:'连接成功'}).waitFor();
  assert.equal(requests,1);
  await vector.getByRole('button',{name:'保存配置',exact:true}).click();
  await page.getByRole('status').filter({hasText:'配置已保存'}).waitFor();
  const saved=await (await context.request.get(`${base}/api/settings/metric-embedding`)).json();
  assert.equal(saved.config.enabled,true);assert.equal(saved.config.apiKeyConfigured,true);assert.ok(!JSON.stringify(saved).includes('fixture-secret'));
  await page.getByRole('button',{name:'重建当前租户索引',exact:true}).click();
  await page.getByRole('status').filter({hasText:'索引完成'}).waitFor();
  assert.ok(requests>1);
  await page.screenshot({path:path.join(root,'metric-settings.png'),fullPage:true});
  await vector.getByRole('switch').click();
  await vector.getByRole('button',{name:'保存配置',exact:true}).click();
  await page.getByRole('status').filter({hasText:'配置已保存'}).waitFor();
  const before=requests;
  const disabled=await context.request.post(`${base}/api/settings/metric-embedding`,{data:{action:'reindex'}});
  assert.ok((await disabled.json()).message.includes('未启用'));
  assert.equal(requests,before);
  await page.reload();await page.getByRole('button',{name:'模型配置',exact:true}).click();
  assert.equal(await vector.getByRole('switch').getAttribute('aria-checked'),'false');
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({ok:true,requests,checks:['401 unauthenticated','403 tenant admin','settings form render','connection test','saved key not exposed','enabled index requests','disabled no requests','persisted switch','no browser errors']},null,2));
} finally {
  await context.request.post(`${base}/api/settings/metric-embedding`,{data:{action:'save',enabled:false,baseUrl:'',model:'',clearApiKey:true}});
  db.prepare("UPDATE tenant_user SET role=? WHERE username='admin'").run(original.role);db.close();
  await browser.close();await new Promise(resolve=>server.close(resolve));
}
