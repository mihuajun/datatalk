import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { createServer } from 'node:http';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE_PATH||'playwright');
const root=path.resolve('.workbuddy-local/metric-governance');
const db=new DatabaseSync(path.join(root,'test.sqlite'));
const original=db.prepare("SELECT role FROM tenant_user WHERE username='admin'").get();
const server=createServer(async(req,res)=>{for await(const chunk of req){}res.setHeader('content-type','application/json');res.end(JSON.stringify({choices:[{message:{content:'red'}}]}));});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
try{
 db.prepare("UPDATE tenant_user SET role='administrator' WHERE username='admin'").run();
 const context=await browser.newContext({viewport:{width:1440,height:1050}});
 await context.request.post('http://127.0.0.1:3010/api/login',{data:{username:'admin',password:'admin'}});
 const page=await context.newPage();let installed=false;const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/api/settings/agent-runtime',route=>route.fulfill({json:{runtime:{installed,running:false,installing:false,state:installed?'installed':'not_installed'}}}));
 await page.goto('http://127.0.0.1:3010/settings');
 await page.getByRole('button',{name:'模型配置',exact:true}).click();
 await page.getByText('请先安装 Agent Runtime，再配置模型。',{exact:true}).waitFor();
 installed=true;await page.reload();await page.getByRole('button',{name:'模型配置',exact:true}).click();
 await page.locator('#agent-model-config').getByLabel('服务地址（OpenAI 兼容）',{exact:true}).fill(`http://127.0.0.1:${server.address().port}/v1`);
 await page.locator('#agent-model-config').getByLabel('模型名称',{exact:true}).fill('fixture-chat');
 await page.locator('#agent-model-config').getByLabel('API Key',{exact:false}).fill('fixture-key');
 await page.locator('#agent-model-config').getByRole('button',{name:'保存配置',exact:true}).click();
 await page.getByRole('status').filter({hasText:'已保存'}).waitFor();
 const runtime=path.join(root,'workspace/runtime/agent-runtime');
 const model=JSON.parse(fs.readFileSync(path.join(runtime,'model.json'),'utf8'));
 assert.equal(model.model,'fixture-chat');
 const files=[];function walk(dir){for(const item of fs.readdirSync(dir,{withFileTypes:true})){const p=path.join(dir,item.name);if(item.isDirectory())walk(p);else if(/ya?ml$/.test(p))files.push(p);}}walk(path.join(runtime,'home'));
 assert.ok(files.some(p=>fs.readFileSync(p,'utf8').includes('fixture-chat')),'DSH settings written');
 assert.ok(files.some(p=>fs.readFileSync(p,'utf8').includes('fixture-key')),'DSH credentials written');
 assert.equal(await page.getByRole('heading',{name:'向量模型',exact:true}).count(),1);
 assert.equal(await page.getByRole('heading',{name:'图片模型',exact:true}).count(),1);
 assert.equal(await page.getByRole('button',{name:'向量模型',exact:true}).count(),0);
 const image=page.locator('#image-model-config');
 assert.equal(await image.getByRole('switch').getAttribute('aria-checked'),'false');
 await image.getByRole('switch').click();
 await image.getByLabel('模型名称',{exact:false}).fill('unsaved-image-fixture');
 await image.getByRole('switch').click();
 await image.getByText('未保存',{exact:true}).waitFor();
 await image.getByRole('switch').click();
 assert.equal(await image.getByLabel('模型名称',{exact:false}).inputValue(),'unsaved-image-fixture');
 await image.getByRole('switch').click();
 await page.screenshot({path:path.join(root,'model-settings-menu.png'),fullPage:true});
 await page.getByRole('button',{name:'Agent Runtime',exact:true}).click();assert.equal(await page.locator('#agent-model-config').getByLabel('服务地址（OpenAI 兼容）',{exact:true}).count(),0);
 assert.deepEqual(errors,[]);console.log(JSON.stringify({ok:true,checks:['separate model menu','installation dependency','original save API','runtime model.json and YAML credentials/settings written','form absent from runtime tab','no page errors']}));
}finally{db.prepare("UPDATE tenant_user SET role=? WHERE username='admin'").run(original.role);db.close();await browser.close();await new Promise(resolve=>server.close(resolve));}
