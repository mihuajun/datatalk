import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright');
const root=path.resolve(process.env.METRIC_FIXTURE_ROOT || '.workbuddy-local/metric-governance');
const fixture=JSON.parse(await fs.readFile(path.join(root,'acceptance.json'),'utf8'));
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
try {
  const context=await browser.newContext({viewport:{width:1440,height:1050},timezoneId:"Asia/Shanghai"});
  const response=await context.request.post(`${fixture.base}/api/login`,{data:{username:'admin',password:'admin'}});
  assert.equal(response.status(),200);
  const page=await context.newPage();
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`${fixture.base}/metrics`);
  await page.getByRole('heading',{name:'指标语义',exact:true}).waitFor();
  await page.getByText(fixture.name,{exact:true}).click();
  const detail=page.getByRole('complementary', {name: `${fixture.name}详情`, exact:true});
  await detail.getByText('使用历史口径，不自动升级',{exact:false}).waitFor();
  assert.equal(await detail.getByText('查看此版本完整定义',{exact:true}).count(),2);
  const fullContent=await detail.getByTestId('metric-content').innerText();
  assert.ok(fullContent.includes('字段映射：orders.id'));
  assert.ok(fullContent.includes('SUM(amount) * 0.9'));
  assert.ok(fullContent.includes('未确认事项：'));
  await detail.getByText('语义内容',{exact:true}).waitFor();
  await detail.getByText('查看此版本完整定义',{exact:true}).last().click();
  await page.screenshot({path:path.join(root,'metric-detail.png'),fullPage:true});
  await page.getByRole('button',{name:'关闭',exact:true}).click();
  const row=page.getByRole('row').filter({has:page.getByText(fixture.name,{exact:true})});
  await row.getByRole('button',{name:'归档',exact:true}).click();
  await page.getByRole('button',{name:'已归档',exact:true}).click();
  const archived=page.getByRole('row').filter({has:page.getByText(fixture.name,{exact:true})});
  await archived.getByRole('button',{name:`删除${fixture.name}`,exact:true}).click();
  await page.getByRole('button',{name:'确认删除',exact:true}).click();
  await page.getByRole('alert').getByText('仅已归档且无在用报表引用的指标可以删除').waitFor();
  await page.screenshot({path:path.join(root,'metric-delete-guard.png'),fullPage:true});
  await archived.getByRole('button',{name:'恢复',exact:true}).click();
  await page.getByRole('button',{name:'有效',exact:true}).click();
  await page.getByText(fixture.name,{exact:true}).waitFor();
  await page.screenshot({path:path.join(root,'metric-list.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.getByText(fixture.name,{exact:true}).click();
  await page.getByTestId('metric-content').waitFor();
  const bounds=await page.getByRole('complementary', {name: `${fixture.name}详情`, exact:true}).boundingBox();
  assert.ok(bounds && Math.abs(bounds.y)<1 && bounds.width<=390 && bounds.height<=844,JSON.stringify(bounds));
  await page.screenshot({path:path.join(root,'metric-mobile-detail.png'),fullPage:false});
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({ok:true,checks:['rendered metrics table','two report names and pinned versions','expand immutable history','archive via UI','delete blocked by API and visible alert','restore via UI','no browser page errors'],screenshots:root},null,2));
} finally { await browser.close(); }
